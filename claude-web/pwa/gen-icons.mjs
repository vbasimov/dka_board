#!/usr/bin/env node
/**
 * Zero-dependency PNG icon generator for the Claude Workspace PWA.
 *
 * The target host has no ImageMagick/rsvg/Inkscape/PIL/canvas/Chromium, so the
 * icons are rendered here with plain Node: a tiny RGBA rasteriser plus a minimal
 * PNG encoder (zlib + CRC32). No third-party packages, no network.
 *
 * The mark is our own glyph — a terminal prompt (chevron + cursor bar) inside a
 * thin ring on the dark app background. It is deliberately NOT the Anthropic
 * logo: that glyph is a trademark and must not be used for this UI.
 *
 * Output (committed artifacts, regenerated by `node pwa/gen-icons.mjs`):
 *   pwa/public/claude/icons/icon-192.png           192x192  purpose "any"
 *   pwa/public/claude/icons/icon-512.png           512x512  purpose "any"
 *   pwa/public/claude/icons/icon-maskable-512.png  512x512  purpose "maskable"
 *   pwa/public/claude/icons/apple-touch-icon-180.png 180x180
 *   pwa/public/claude/icons/favicon-96.png          96x96
 *
 * All five are opaque RGB(A) PNGs on #1a1917; the mark stays inside the safe
 * zone (radius <= 40% of the side) so the maskable icon survives any mask.
 */
import { deflateSync } from 'node:zlib';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const pwaDir = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(pwaDir, 'public', 'claude', 'icons');

/** #1a1917 — the manifest theme/background colour, must match exactly. */
const BACKGROUND = [0x1a, 0x19, 0x17];
/** Warm amber accent; our own palette, not an Anthropic brand colour. */
const ACCENT = [0xe0, 0xa4, 0x58];

// ---------------------------------------------------------------------------
// Vector mark in unit coordinates: centre (0,0), artwork inside +-0.22.
// The maskable safe zone is a circle of radius 0.4, so 0.22 < 0.4 with margin.
// ---------------------------------------------------------------------------
const MARK_RADIUS = 0.021; // half stroke width of the chevron and the bar
const RING_RADIUS = 0.31;
const RING_HALF = 0.0085;
const RING_OPACITY = 0.42;

/** Distance from point (px,py) to segment (ax,ay)-(bx,by). */
function segmentDistance(px, py, ax, ay, bx, by) {
  const pax = px - ax;
  const pay = py - ay;
  const bax = bx - ax;
  const bay = by - ay;
  const lenSq = bax * bax + bay * bay;
  const h = lenSq === 0 ? 0 : Math.max(0, Math.min(1, (pax * bax + pay * bay) / lenSq));
  return Math.hypot(pax - bax * h, pay - bay * h);
}

/** Anti-aliased coverage of a stroke of half-width `half` at signed distance `d`. */
function strokeCoverage(distance, half, aaWidth) {
  return Math.max(0, Math.min(1, (half - distance) / aaWidth + 0.5));
}

/**
 * Render one icon as raw RGBA rows (top-down, no filter bytes).
 * `scale` lets maskable variants shrink the mark a little; 1 keeps it as is.
 */
function renderRgba(size, scale = 1) {
  const pixels = Buffer.alloc(size * size * 4);
  const aa = 0.8 / size; // ~1.6 px of anti-aliasing, constant in device pixels
  const s = 1 / scale;

  for (let y = 0; y < size; y += 1) {
    for (let x = 0; x < size; x += 1) {
      // Pixel centre in unit coordinates (-0.5 .. 0.5).
      const cx = ((x + 0.5) / size - 0.5) * s;
      const cy = ((y + 0.5) / size - 0.5) * s;

      // Prompt chevron ">": two strokes meeting at the tip.
      const chevron = Math.min(
        segmentDistance(cx, cy, -0.20, -0.13, -0.06, 0),
        segmentDistance(cx, cy, -0.20, 0.13, -0.06, 0),
      );
      // Cursor bar to the right of the chevron.
      const bar = segmentDistance(cx, cy, 0.02, 0.135, 0.20, 0.135);

      let mark = strokeCoverage(Math.min(chevron, bar), MARK_RADIUS, aa);
      const ringDistance = Math.abs(Math.hypot(cx, cy) - RING_RADIUS);
      const ring = strokeCoverage(ringDistance, RING_HALF, aa) * RING_OPACITY;
      const coverage = Math.max(mark, ring);

      const offset = (y * size + x) * 4;
      for (let channel = 0; channel < 3; channel += 1) {
        pixels[offset + channel] = Math.round(
          BACKGROUND[channel] + (ACCENT[channel] - BACKGROUND[channel]) * coverage,
        );
      }
      pixels[offset + 3] = 0xff; // fully opaque: installers dislike transparency
    }
  }
  return pixels;
}

// ---------------------------------------------------------------------------
// Minimal PNG encoder: signature, IHDR, one IDAT (filter 0 per scanline), IEND.
// ---------------------------------------------------------------------------
const CRC_TABLE = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n += 1) {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(buffer) {
  let c = 0xffffffff;
  for (let i = 0; i < buffer.length; i += 1) c = CRC_TABLE[(c ^ buffer[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length, 0);
  const typeAndData = Buffer.concat([Buffer.from(type, 'latin1'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(typeAndData), 0);
  return Buffer.concat([length, typeAndData, crc]);
}

function encodePng(size, rgba) {
  const signature = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type: truecolour with alpha (RGBA)
  ihdr[10] = 0; // deflate
  ihdr[11] = 0; // adaptive filtering
  ihdr[12] = 0; // no interlace

  // Raw scanlines with filter byte 0 (None) in front of each row.
  const stride = size * 4;
  const raw = Buffer.alloc(size * (stride + 1));
  for (let y = 0; y < size; y += 1) {
    raw[y * (stride + 1)] = 0;
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }

  const idat = deflateSync(raw, { level: 9 });
  return Buffer.concat([
    signature,
    chunk('IHDR', ihdr),
    chunk('IDAT', idat),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// ---------------------------------------------------------------------------
// Emit the five install assets.
// ---------------------------------------------------------------------------
const TARGETS = [
  { name: 'icon-192.png', size: 192, scale: 1 },
  { name: 'icon-512.png', size: 512, scale: 1 },
  // Maskable: the launcher may crop to a circle; keep the mark a bit smaller
  // than the safe zone so a circular mask never clips the ring.
  { name: 'icon-maskable-512.png', size: 512, scale: 0.92 },
  { name: 'apple-touch-icon-180.png', size: 180, scale: 1 },
  { name: 'favicon-96.png', size: 96, scale: 1 },
];

mkdirSync(iconsDir, { recursive: true });
for (const target of TARGETS) {
  const png = encodePng(target.size, renderRgba(target.size, target.scale));
  writeFileSync(join(iconsDir, target.name), png);
  process.stdout.write(`[icons] ${target.name} ${target.size}x${target.size} ${png.length} B\n`);
}
process.stdout.write(`[icons] готово: ${iconsDir}\n`);
